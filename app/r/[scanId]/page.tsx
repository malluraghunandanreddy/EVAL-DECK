import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { eq } from "drizzle-orm";
import { db, schema } from "@/lib/db";
import { headline } from "@/lib/checklist";
import type { ChecklistItem, Framework, Gap } from "@/lib/types";
import { FRAMEWORK_LABEL, SEVERITIES, SEVERITY_LABEL, STATUS_META, arr, frameworksOf } from "@/lib/report/format";
import "../../scan/report.css";

export const dynamic = "force-dynamic";
export const metadata: Metadata = { title: "Privacy checklist · PolicyDrift", robots: { index: false } };

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

async function load(scanId: string) {
  if (!UUID_RE.test(scanId)) return null;
  const [row] = await db
    .select({
      status: schema.scans.status,
      checklist: schema.scans.checklist,
      gaps: schema.scans.gaps,
      finishedAt: schema.scans.finishedAt,
      projectName: schema.projects.name,
      frameworks: schema.projects.frameworks,
    })
    .from(schema.scans)
    .innerJoin(schema.projects, eq(schema.projects.id, schema.scans.projectId))
    .where(eq(schema.scans.id, scanId))
    .limit(1);
  return row ?? null;
}

export default async function PublicReport({ params }: { params: Promise<{ scanId: string }> }) {
  const { scanId } = await params;
  const row = await load(scanId);
  if (!row) notFound();

  // Public view: statuses and titles only. Never evidence, snippets or fixes.
  const items = arr(row.checklist as ChecklistItem[] | null).map((i) => ({
    id: i.id, framework: i.framework, title: i.title, lawRef: i.lawRef, status: i.status, gapIds: arr(i.gapIds),
  }));
  const gaps = arr(row.gaps as Gap[] | null).map((g) => ({ id: g.id, title: g.title, severity: g.severity }));
  const frameworks = frameworksOf(items, row.frameworks as Framework[]);

  return (
    <main className="rp">
      <div className="rp-header">
        <div>
          <div className="muted" style={{ fontSize: 13 }}>Shared privacy checklist</div>
          <h1>{row.projectName}</h1>
          <div className="rp-meta">
            {frameworks.map((f) => <span key={f} className="rp-pill">{FRAMEWORK_LABEL[f]}</span>)}
            {row.finishedAt && <span className="rp-pill">Scanned {row.finishedAt.toISOString().slice(0, 10)}</span>}
          </div>
        </div>
        <div className="rp-actions">
          <a className="btn sm" href="/">Check your own app</a>
        </div>
      </div>

      {row.status !== "done" ? (
        <div className="panel rp-section rp-empty">This scan is not finished yet.</div>
      ) : (
        <>
          {frameworks.map((f) => {
            const mine = items.filter((i) => i.framework === f);
            if (!mine.length) return null;
            return (
              <section key={f} className="rp-section">
                <p className="rp-headline">{headline(items as ChecklistItem[], f)}</p>
                <ul className="rp-list" style={{ marginTop: 12 }}>
                  {mine.map((i) => {
                    const meta = STATUS_META[i.status];
                    return (
                      <li key={i.id} className={`rp-item ${i.status}`}>
                        <div className="rp-item-row">
                          <span className={`rp-status ${i.status}`} aria-label={meta.label}>{meta.icon}</span>
                          <div className="rp-item-body">
                            <div className="rp-item-title">{i.title}</div>
                            <div className="rp-item-sub"><span className="rp-law">{i.lawRef}</span><span>{meta.label}</span></div>
                          </div>
                        </div>
                      </li>
                    );
                  })}
                </ul>
              </section>
            );
          })}

          <section className="rp-section">
            <h2>Issues found ({gaps.length})</h2>
            {gaps.length === 0 && <div className="panel rp-empty">No issues found.</div>}
            {SEVERITIES.map((sev) => {
              const group = gaps.filter((g) => g.severity === sev);
              if (!group.length) return null;
              return (
                <div key={sev} className="rp-sev-group">
                  <h3><span className={`rp-chip ${sev}`}>{SEVERITY_LABEL[sev]}</span> {group.length}</h3>
                  {group.map((g) => (
                    <div key={g.id} className="rp-gap"><p className="rp-gap-title" style={{ margin: 0 }}>{g.title}</p></div>
                  ))}
                </div>
              );
            })}
          </section>
        </>
      )}

      <p className="rp-note">Generated by PolicyDrift, an automated check of code, schema and policy text. Not legal advice.</p>
    </main>
  );
}
